"""Figure 4b: requirement of the multi-table templates of the ten further applications.

Per app, the share of templates (outside test and development code) that need only order under both
readings, need atomic visibility only if derived values must be exact (strict reading), need atomic
visibility under both readings (copies), and are unconstrained.  Writes the pgfplots axis of panel
(b) and its description text, and prints the counts.
Reads <out dir>/<app>.json or <app>.json.gz.
Usage: python -I fig_apps.py <out dir> <panel.tex>"""
import gzip, json, os, re, sys
from collections import Counter

sys.stdout.reconfigure(encoding='utf-8')
out, panel = sys.argv[1:3]
APPS = [('zulip', 'Zulip'), ('makeplane', 'Plane'), ('saleor', 'Saleor'), ('openedx', 'Open edX'),
        ('PostHog', 'PostHog'), ('chatwoot', 'Chatwoot'), ('mastodon', 'Mastodon'),
        ('discourse', 'Discourse'), ('spree', 'Spree'), ('instructure', 'Canvas')]
KEYS = ('order', 'derived', 'copy', 'none')
TESTDEV = re.compile(r'(^|/)(tests?|spec|testing_support|factories|fixtures|development|seeders?|seeds?|test_utils?'
                     r'|testing)(/|\.|_)|random_data|curl_param_value_generators|/demo/')


def load(app):
    p = os.path.join(out, app + '.json')
    if os.path.exists(p):
        return json.load(open(p, encoding='utf-8'))
    return json.load(gzip.open(p + '.gz', 'rt', encoding='utf-8'))


rows = []
for app, name in APPS:
    ts = [t for t in load(app)['templates'] if t['kind'] == 'event' or not TESTDEV.search(t['origin'])]
    c = Counter()
    for t in ts:
        if t['oneway'] == 'atomic':
            c['copy'] += 1
        elif t['strict'] == 'atomic':
            c['derived'] += 1
        else:
            c[t['strict']] += 1
    n = len(ts)
    rows.append((name, n, {k: 100 * c[k] / n for k in KEYS}, c))
rows.sort(key=lambda r: r[2]['order'])     # pgfplots draws the first y coordinate at the bottom
for r in rows[::-1]:
    print('%-9s n=%4d  %s' % (r[0], r[1], dict(r[3])))

coords = lambda k: ' '.join('(%.1f,%s)' % (r[2][k], r[0]) for r in rows)
names = ','.join(r[0] for r in rows)
desc = '; '.join('%s %.0f, %.0f, %.0f and %.0f' % ((r[0],) + tuple(r[2][k] for k in KEYS)) for r in rows[::-1])
tex = r"""%% generated by apps/fig_apps.py from apps/out; do not edit by hand
\begin{tikzpicture}
\begin{axis}[xbar stacked, width=\columnwidth, height=3.4cm, bar width=4.5pt, clip=false, xmin=0, xmax=100,
  axis lines*=left, xmajorgrids, grid style={black!12}, tick label style={font=\scriptsize},
  label style={font=\scriptsize}, xlabel={Share of all multi-table templates (\%%)}, xlabel style={yshift=3pt},
  symbolic y coords={%s}, ytick=data, major y tick style={draw=none}, enlarge y limits=0.07,
  legend style={font=\scriptsize, draw=none, fill=none, at={(rel axis cs:1,1)}, anchor=south east, inner sep=0pt},
  legend image code/.code={\draw[#1, draw=none] (0cm,-0.08cm) rectangle (0.2cm,0.1cm);}]
\node[font=\scriptsize\bfseries, anchor=south west, inner sep=0pt] at (rel axis cs:0,1.03) {(b)};
\addplot[fill=cOrder, draw=none, forget plot] coordinates {%s};
\addplot[pattern=north east lines, pattern color=cAtomic, draw=none] coordinates {%s};
\addplot[fill=cAtomic, draw=none, forget plot] coordinates {%s};
\addplot[fill=cNone, draw=none, forget plot] coordinates {%s};
\addlegendentry{atomic only if derived values are exact}
\end{axis}
\end{tikzpicture}
""" % (names, coords('order'), coords('derived'), coords('copy'), coords('none'))
open(panel, 'w', encoding='utf-8', newline='\n').write(tex)
open(os.path.splitext(panel)[0] + '_desc.txt', 'w', encoding='utf-8', newline='\n').write(desc + '\n')
print(desc)
